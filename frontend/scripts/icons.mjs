function path(weight, name) {
  const file = weight === "regular" ? `${name}.svg` : `${name}-${weight}.svg`;
  const svg = readFileSync(join(assets, weight, file), "utf8");
  const ds = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!ds.length || /<(circle|rect|line|polyline|polygon|ellipse)\b/.test(svg)) throw new Error(`${file}: expected path-only SVG`);
  return ds.join("");
}

const icons = Object.entries(ICONS)
  .map(([app, ph]) => `  ${app}: { regular: ${JSON.stringify(path("regular", ph))}, bold: ${JSON.stringify(path("bold", ph))}, fill: ${JSON.stringify(path("fill", ph))} },`)
  .join("\n");
const glyphs = Object.entries(GLYPHS)
  .map(([app, ph]) => `  ${app}: ${JSON.stringify(path("fill", ph))},`)
  .join("\n");

writeFileSync(
  new URL("../src/components/icons.generated.ts", import.meta.url),
  `// Generated by scripts/icons.mjs from Phosphor Icons (MIT, https://phosphoricons.com). Don't edit by hand.
// Paths on a 256-unit grid.

export const ICON_PATHS = {
${icons}
} as const;

export const GLYPH_PATHS = {
${glyphs}
} as const;
`,
);
